print(f"    P95 latency    : {np.percentile(lat_arr, 95):.3f} ms")
print(f"    P99 latency    : {np.percentile(lat_arr, 99):.3f} ms")
print(f"    Min latency    : {lat_arr.min():.3f} ms")
print(f"    Max latency    : {lat_arr.max():.3f} ms")

# ── 6. Throughput ────────────────────────────────────────────────────────────
print(f"\n[6] Throughput — images / second  (batch sizes: 1, 8, 16, 32, 64)")
batch_sizes        = [1, 8, 16, 32, 64]
throughput_results = {}

for bs in batch_sizes:
    try:
        model_ext.eval()                          # ensure eval before each batch
        batch = torch.randn(bs, 3, img_size, img_size).to(DEVICE)
        with torch.no_grad():
            for _ in range(10):                   # warm-up
                _ = model_ext(batch)
        if DEVICE.type == 'cuda':
            torch.cuda.synchronize()

        REPS = 50
        t0   = time.perf_counter()
        with torch.no_grad():
            for _ in range(REPS):
                _ = model_ext(batch)
        if DEVICE.type == 'cuda':
            torch.cuda.synchronize()
        elapsed = time.perf_counter() - t0

        ips = (bs * REPS) / elapsed
        throughput_results[bs] = ips
        print(f"    Batch size {bs:>3} → {ips:>9,.1f} images/sec")
        del batch
    except RuntimeError as oom:
        print(f"    Batch size {bs:>3} → OOM: {oom}")
        throughput_results[bs] = None

if DEVICE.type == 'cuda':
    torch.cuda.empty_cache()

# ── 7. Full-dataset Average Inference Time ───────────────────────────────────
