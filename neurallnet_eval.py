class SEBlock(nn.Module):
    def __init__(self, channels, reduction=4):
        super().__init__()
        mid = max(channels // reduction, 8)
        self.squeeze   = nn.AdaptiveAvgPool2d(1)
        self.excitation = nn.Sequential(
            nn.Linear(channels, mid, bias=False),
            nn.ReLU(inplace=True),
            nn.Linear(mid, channels, bias=False),
            nn.Sigmoid()
        )

    def forward(self, x):
        b, c, _, _ = x.shape
        w = self.squeeze(x).view(b, c)
        w = self.excitation(w).view(b, c, 1, 1)
        return x * w


class DepthwiseSeparableConv(nn.Module):
    def __init__(self, in_ch, out_ch, kernel_size=3, stride=1, padding=1):
        super().__init__()
        self.depthwise = nn.Conv2d(in_ch, in_ch, kernel_size, stride=stride,
                                   padding=padding, groups=in_ch, bias=False)
        self.bn_dw     = nn.BatchNorm2d(in_ch)
        self.pointwise = nn.Conv2d(in_ch, out_ch, 1, bias=False)
        self.bn_pw     = nn.BatchNorm2d(out_ch)

    def forward(self, x):
        x = self.bn_dw(self.depthwise(x))
        x = self.bn_pw(self.pointwise(x))
        return x


class SpikeBlock(nn.Module):
    def __init__(self, in_ch, out_ch, tau=2.0, pool=True):
        super().__init__()
        self.conv = DepthwiseSeparableConv(in_ch, out_ch)
        self.se   = SEBlock(out_ch)
        self.lif  = neuron.LIFNode(tau=tau, surrogate_function=surrogate.ATan(),
                                   step_mode='s', backend='torch')
        self.pool = nn.MaxPool2d(2, 2) if pool else nn.Identity()

    def forward(self, x):
        x = self.conv(x)
        x = self.se(x)
        x = self.lif(x)
        x = self.pool(x)
        return x


class CSNN_Student_v2(nn.Module):
    def __init__(self, num_classes=4, time_steps=4):
        super().__init__()
        self.T = time_steps
        tau    = 2.0

        self.stem = nn.Sequential(
            nn.Conv2d(3, 48, kernel_size=3, padding=1, bias=False),
            nn.BatchNorm2d(48),
            neuron.LIFNode(tau=tau, surrogate_function=surrogate.ATan(),
                           step_mode='s', backend='torch'),
            nn.MaxPool2d(2, 2),
        )

        self.block1 = SpikeBlock(48,  96,  tau=tau, pool=True)
        self.block2 = SpikeBlock(96,  192, tau=tau, pool=True)
        self.block3 = SpikeBlock(192, 384, tau=tau, pool=True)

        self.refine = nn.Sequential(
            nn.Conv2d(384, 384, kernel_size=3, padding=1, groups=384, bias=False),
            nn.BatchNorm2d(384),
            nn.Conv2d(384, 256, 1, bias=False),
            nn.BatchNorm2d(256),
            neuron.LIFNode(tau=tau, surrogate_function=surrogate.ATan(),
                           step_mode='s', backend='torch'),
        )

        self.gap = nn.AdaptiveAvgPool2d(1)

        self.classifier = nn.Sequential(
            nn.Linear(256, 128, bias=False),
            nn.BatchNorm1d(128),
            neuron.LIFNode(tau=tau, surrogate_function=surrogate.ATan(),
                           step_mode='s', backend='torch'),
            nn.Dropout(0.3),
            nn.Linear(128, num_classes, bias=False),
        )

    def forward(self, x):
        output_sum = None
        for t in range(self.T):
            functional.reset_net(self)
            y   = self.stem(x)
            y   = self.block1(y)
            y   = self.block2(y)
            y   = self.block3(y)
            y   = self.refine(y)
            y   = self.gap(y).flatten(1)
            out = self.classifier(y)
            output_sum = out if output_sum is None else output_sum + out
            del y
        return output_sum / self.T


