# ── 5. Single-image Latency ──────────────────────────────────────────────────
print(f"\n[5] Single-Image Inference Latency  (500 runs, batch size = 1)")
model_ext.eval()
N_RUNS    = 500
latencies = []
with torch.no_grad():
    for _ in range(N_RUNS):
        if DEVICE.type == 'cuda':
            torch.cuda.synchronize()
        t0 = time.perf_counter()
        _ = model_ext(dummy_input)
        if DEVICE.type == 'cuda':
            torch.cuda.synchronize()
        latencies.append((time.perf_counter() - t0) * 1000)   # ms

