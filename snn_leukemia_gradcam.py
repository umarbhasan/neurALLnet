class SNNGradCAM:
    """
    Grad-CAM implementation fixed for Spiking Neural Networks.

    Key fixes:
    1. Forces surrogate gradients by temporarily setting model to train() mode.
    2. Keeps all BatchNorm layers in eval() mode → safe for batch_size=1.
    3. Handles temporal dimension (time steps) properly.
    4. Restores original model mode after CAM generation.
    """
    def __init__(self, model, target_layer):
        self.model = model
        self.target_layer = target_layer
        self.gradients = []
        self.activations = []

        # Register hooks
        self.forward_hook = target_layer.register_forward_hook(self.save_activation)
        self.backward_hook = target_layer.register_full_backward_hook(self.save_gradient)

    def save_activation(self, module, input, output):
        """Save activations during forward pass"""
        self.activations.append(output.detach().clone())

    def save_gradient(self, module, grad_input, grad_output):
        """Save gradients during backward pass"""
        self.gradients.append(grad_output[0].detach().clone())

    def generate_cam(self, input_image, target_class=None):
        """
        Generate Grad-CAM heatmap for SNN with forced surrogate gradients.
        """
        # Clear previous hooks data
        self.gradients = []
        self.activations = []

        # Store original model mode
        orig_mode = self.model.training

        try:
            # ---------- FIX: Force surrogate gradients ----------
            # 1. Set entire model to train mode → surrogate gradients active
            self.model.train()

            # 2. Put all BatchNorm layers in eval mode → stable statistics
            def set_bn_eval(module):
                if isinstance(module, (torch.nn.BatchNorm1d,
                                       torch.nn.BatchNorm2d,
                                       torch.nn.BatchNorm3d)):
                    module.eval()
            self.model.apply(set_bn_eval)
            # ----------------------------------------------------

            # Enable gradient computation (already True, but explicit)
            with torch.set_grad_enabled(True):
                # Forward pass
                output = self.model(input_image)

                # Get target class
                if target_class is None:
                    target_class = output.argmax(dim=1).item()

                # Backward pass for target class
                self.model.zero_grad()
                one_hot = torch.zeros_like(output)
                one_hot[0][target_class] = 1.0
                output.backward(gradient=one_hot, retain_graph=False)

        finally:
            # Restore original model mode (train/eval)
            if orig_mode:
                self.model.train()
            else:
                self.model.eval()

        # ---------- Check if gradients were captured ----------
        if len(self.gradients) == 0 or len(self.activations) == 0:
            print(f"   ⚠️  No gradients captured for class {target_class}")
            return None

        # Aggregate gradients and activations across time steps
        if len(self.gradients) > 1:
            gradients = torch.stack(self.gradients).mean(dim=0)
            activations = torch.stack(self.activations).mean(dim=0)
        else:
            gradients = self.gradients[0]
            activations = self.activations[0]

        # Global average pooling on gradients → weights
        weights = gradients.mean(dim=(2, 3), keepdim=True)

        # Weighted combination of activation maps
        cam = (weights * activations).sum(dim=1, keepdim=True)

        # Apply ReLU
        cam = F.relu(cam)

        # Normalize to [0,1]
        cam_min = cam.min()
        cam_max = cam.max()
        if cam_max > cam_min:
            cam = (cam - cam_min) / (cam_max - cam_min + 1e-8)
        else:
            cam = torch.ones_like(cam) * 0.5

        return cam

    def remove_hooks(self):
        """Remove registered hooks"""
        self.forward_hook.remove()
        self.backward_hook.remove()


