def _lif(tau=2.0):
    return neuron.LIFNode(tau=tau, surrogate_function=surrogate.ATan(),
                          step_mode='s', backend='torch')

def _dsconv(ic, oc):
    return nn.Sequential(
        nn.Conv2d(ic, ic, 3, padding=1, groups=ic, bias=False), nn.BatchNorm2d(ic),
        nn.Conv2d(ic, oc, 1, bias=False), nn.BatchNorm2d(oc))

def _se(ch):
    mid = max(ch // 4, 8)
    return nn.Sequential(nn.AdaptiveAvgPool2d(1))  # placeholder — full SE below

class SEFull(nn.Module):
    def __init__(self, ch):
        super().__init__()
        mid = max(ch // 4, 8)
        self.sq = nn.AdaptiveAvgPool2d(1)
        self.ex = nn.Sequential(nn.Linear(ch, mid, bias=False), nn.ReLU(inplace=True),
                                 nn.Linear(mid, ch, bias=False), nn.Sigmoid())
    def forward(self, x):
        b, c = x.shape[:2]
        return x * self.ex(self.sq(x).view(b, c)).view(b, c, 1, 1)

# ── variant factory ───────────────────────────────────────────────────────
def build_variant(use_se=True, use_refine=True, head_units=128, use_bn_head=True):
    class _M(nn.Module):
        def __init__(self):
            super().__init__()
            tau = 2.0; T = time_steps
            self.T = T
            self.stem = nn.Sequential(
                nn.Conv2d(3, 48, 3, padding=1, bias=False), nn.BatchNorm2d(48),
                _lif(tau), nn.MaxPool2d(2, 2))
            self.blocks = nn.ModuleList()
            for ic, oc in [(48, 96), (96, 192), (192, 384)]:
                blk = nn.ModuleDict({
                    'conv': _dsconv(ic, oc),
                    'se':   SEFull(oc) if use_se else nn.Identity(),
                    'lif':  _lif(tau),
                    'pool': nn.MaxPool2d(2, 2)})
                self.blocks.append(blk)
            if use_refine:
                self.refine = nn.Sequential(
                    nn.Conv2d(384, 384, 3, padding=1, groups=384, bias=False),
                    nn.BatchNorm2d(384), nn.Conv2d(384, 256, 1, bias=False),
                    nn.BatchNorm2d(256), _lif(tau))
                feat_dim = 256
            else:
                self.refine = nn.Identity()
                feat_dim = 384
            self.gap = nn.AdaptiveAvgPool2d(1)
            head = [nn.Linear(feat_dim, head_units, bias=False)]
            if use_bn_head:
                head.append(nn.BatchNorm1d(head_units))
            head += [_lif(tau), nn.Dropout(0.3),
                     nn.Linear(head_units, num_classes, bias=False)]
            self.classifier = nn.Sequential(*head)

        def forward(self, x):
            out_sum = None
            for _ in range(self.T):
                functional.reset_net(self)
                y = self.stem(x)
                for blk in self.blocks:
                    y = blk['conv'](y); y = blk['se'](y)
                    y = blk['lif'](y);  y = blk['pool'](y)
                y = self.refine(y)
                y = self.gap(y).flatten(1)
                o = self.classifier(y)
                out_sum = o if out_sum is None else out_sum + o
                del y
            return out_sum / self.T
    return _M().to(DEVICE)


