# ── helper: build a fresh SNN model with configurable dropout ─────────────
def build_snn(dropout_rate=0.3, num_classes=4, time_steps=4):
    class _SEBlock(nn.Module):
        def __init__(self, channels, reduction=4):
            super().__init__()
            mid = max(channels // reduction, 8)
            self.squeeze = nn.AdaptiveAvgPool2d(1)
            self.excitation = nn.Sequential(
                nn.Linear(channels, mid, bias=False), nn.ReLU(inplace=True),
                nn.Linear(mid, channels, bias=False), nn.Sigmoid()
            )
        def forward(self, x):
            b, c, _, _ = x.shape
            w = self.squeeze(x).view(b, c)
            return x * self.excitation(w).view(b, c, 1, 1)

    class _DSConv(nn.Module):
        def __init__(self, in_ch, out_ch):
            super().__init__()
            self.dw = nn.Conv2d(in_ch, in_ch, 3, padding=1, groups=in_ch, bias=False)
            self.bn_dw = nn.BatchNorm2d(in_ch)
            self.pw = nn.Conv2d(in_ch, out_ch, 1, bias=False)
            self.bn_pw = nn.BatchNorm2d(out_ch)
        def forward(self, x):
            return self.bn_pw(self.pw(self.bn_dw(self.dw(x))))

    class _SpikeBlock(nn.Module):
        def __init__(self, in_ch, out_ch, tau=2.0):
            super().__init__()
            self.conv = _DSConv(in_ch, out_ch)
            self.se   = _SEBlock(out_ch)
            self.lif  = neuron.LIFNode(tau=tau, surrogate_function=surrogate.ATan(),
                                       step_mode='s', backend='torch')
            self.pool = nn.MaxPool2d(2, 2)
        def forward(self, x):
            x = self.conv(x); x = self.se(x); x = self.lif(x); x = self.pool(x)
            return x

    class _Model(nn.Module):
        def __init__(self):
            super().__init__()
            tau = 2.0
            self.T = time_steps
            self.stem = nn.Sequential(
                nn.Conv2d(3, 48, 3, padding=1, bias=False), nn.BatchNorm2d(48),
                neuron.LIFNode(tau=tau, surrogate_function=surrogate.ATan(),
                               step_mode='s', backend='torch'),
                nn.MaxPool2d(2, 2))
            self.b1 = _SpikeBlock(48,  96,  tau)
            self.b2 = _SpikeBlock(96,  192, tau)
            self.b3 = _SpikeBlock(192, 384, tau)
            self.refine = nn.Sequential(
                nn.Conv2d(384, 384, 3, padding=1, groups=384, bias=False),
                nn.BatchNorm2d(384),
                nn.Conv2d(384, 256, 1, bias=False), nn.BatchNorm2d(256),
                neuron.LIFNode(tau=tau, surrogate_function=surrogate.ATan(),
                               step_mode='s', backend='torch'))
            self.gap = nn.AdaptiveAvgPool2d(1)
            self.classifier = nn.Sequential(
                nn.Linear(256, 128, bias=False), nn.BatchNorm1d(128),
                neuron.LIFNode(tau=tau, surrogate_function=surrogate.ATan(),
                               step_mode='s', backend='torch'),
                nn.Dropout(dropout_rate),
                nn.Linear(128, num_classes, bias=False))
        def forward(self, x):
            out_sum = None
            for _ in range(self.T):
                functional.reset_net(self)
                y = self.stem(x); y = self.b1(y); y = self.b2(y)
                y = self.b3(y);   y = self.refine(y)
                y = self.gap(y).flatten(1); o = self.classifier(y)
                out_sum = o if out_sum is None else out_sum + o
                del y
            return out_sum / self.T

    return _Model().to(DEVICE)

# ── helper: quick train + eval with specified optimizer ──────────────────
def quick_train_eval(mdl, opt_fn, bs=16):
    ld_tr = DataLoader(train_dataset, batch_size=bs, shuffle=True,
                       num_workers=2, pin_memory=True, drop_last=True)
    ld_te = DataLoader(test_dataset,  batch_size=bs, shuffle=False,
                       num_workers=2, pin_memory=True)
    opt   = opt_fn(mdl.parameters())
    crit  = nn.CrossEntropyLoss()
    for ep in range(TUNE_EPOCHS):
        mdl.train()
        for imgs, lbls in ld_tr:
            imgs, lbls = imgs.to(DEVICE), lbls.to(DEVICE)
            opt.zero_grad(); loss = crit(mdl(imgs), lbls)
            loss.backward(); opt.step()
            del imgs, lbls, loss
        torch.cuda.empty_cache(); gc.collect()
    mdl.eval()
    correct, total = 0, 0
    with torch.no_grad():
        for imgs, lbls in ld_te:
            imgs = imgs.to(DEVICE)
            preds  = torch.argmax(mdl(imgs), dim=1).cpu()
            correct += (preds == lbls).sum().item()
            total   += lbls.size(0)
    return correct / total

